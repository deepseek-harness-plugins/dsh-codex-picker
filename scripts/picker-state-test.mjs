import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {readFile, mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {build} from 'esbuild';
import {chromium} from 'playwright';

const project = fileURLToPath(new URL('..', import.meta.url));
const {outputFiles} = await build({bundle: true, write: false, format: 'iife', jsx: 'automatic', stdin: {resolveDir: project, loader: 'jsx', contents: `
  import React from 'react';
  import {createRoot} from 'react-dom/client';
  import {CodexPicker} from './src/picker.jsx';
  const listeners = new Set();
  let state = {current: {provider: 'fixture', model: 'fixture-model', reasoningEffort: 'high'}, groups: [{id: 'fixture', name: 'Fixture', models: [{id: 'fixture-model', name: 'Fixture Model', reasoning: {defaultEffort: 'high', efforts: ['low', 'medium', 'high', 'max'].map(id => ({id, name: id}))}}]}], pending: null, failures: [], error: null};
  state.groups.push({id: 'relay', name: 'Relay', models: [{id:'fixture-model', name:'Fixture Model'}]});
  const directory = {subscribe: fn => {listeners.add(fn); return () => listeners.delete(fn);}, getSnapshot: () => state};
  const update = patch => {state = {...state, ...patch}; for (const fn of listeners) fn();};
  window.completed = 0;
  window.currentSelection = () => state.current;
  const select = async selection => {
    window.samples = [];
    let sampling = true;
    const sample = () => {
      const trigger = document.querySelector('.dcp-picker-trigger'), title = document.querySelector('.dcp-effort-title span'), panel = document.querySelector('.dcp-picker-panel');
      window.samples.push({pending: state.pending !== null, title: title.textContent, triggerOpacity: getComputedStyle(trigger).opacity, rowOpacity: getComputedStyle(document.querySelector('[role=menuitemradio]')).opacity, sliderOpacity: getComputedStyle(document.querySelector('input[type=range]')).opacity, panelOpacity: getComputedStyle(panel).opacity});
      if (sampling) requestAnimationFrame(sample);
    };
    update({pending: selection}); requestAnimationFrame(sample);
    await new Promise(resolve => setTimeout(resolve, 100));
    // The host can finish the RPC before the durable projection arrives.
    update({pending: null});
    await new Promise(resolve => setTimeout(resolve, 100));
    const failed = window.failNext;
    if (!failed) update({current: selection});
    sampling = false; window.completed++;
    return failed ? {ok: false, error: {message: 'Fixture selection failed'}} : {ok: true};
  };
  createRoot(document.querySelector('#root')).render(<CodexPicker locked={false} available={true} directory={directory} load={() => {}} select={select} renderSlot={(name, props) => <>{props.model.name}<span data-badge data-placement={props.placement}>1017</span></>}/>);
`}});
await mkdir(resolve(project, 'test-results'), {recursive:true});
const styles = await readFile(resolve(project, 'src/styles.css'), 'utf8');
const browser = await chromium.launch({channel: process.env.DCP_BROWSER ?? 'chrome', headless: true});
try {
  const page = await browser.newPage({viewport: {width: 900, height: 700}});
  const errors = [];
  page.on('pageerror', error => {errors.push(error.message); console.error('PAGE_ERROR', error.message);});
  await page.setContent(`<style>${styles}</style><div id="root" style="position:fixed;bottom:24px;right:24px"></div><script>${outputFiles[0].text}</script>`);
  const trigger = page.locator('.dcp-picker-trigger');
  await trigger.click();
  const slider = page.getByRole('slider', {name: '思考强度', exact: true});
  await page.waitForTimeout(400);
  const boost = page.getByRole('button', {name:'加速动画', exact:true});
  const originalSelection = await page.evaluate(() => window.currentSelection());
  const originalBounds = await page.getByRole('dialog').boundingBox();
  assert.equal(await boost.getAttribute('aria-pressed'), 'false');
  await boost.click();
  assert.equal(await boost.getAttribute('aria-pressed'), 'true');
  assert.equal(await boost.evaluate(el => getComputedStyle(el).cursor), 'pointer');
  assert.deepEqual(await page.getByRole('dialog').boundingBox(), originalBounds, 'cosmetic boost does not move or resize the menu');
  assert.deepEqual(await page.evaluate(() => window.currentSelection()), originalSelection);
  assert.equal(await page.evaluate(() => window.completed), 0, 'boost never calls the host selection API');
  assert.deepEqual(errors, []);
  assert.equal(await page.locator('.dcp-fast-path').count(),14, await page.locator('body').innerText());
  const startupParticles = await page.locator('.dcp-fast-path').evaluateAll(paths => paths.map(el => {
    const animation = el.getAnimations()[0], previousTime = animation.currentTime;
    animation.pause(); animation.currentTime = 250;
    const x = new DOMMatrix(getComputedStyle(el).transform).m41 / el.getBoundingClientRect().width;
    const opacity = Number(getComputedStyle(el).opacity) * Number(getComputedStyle(el.firstElementChild).opacity);
    animation.currentTime = previousTime; animation.play();
    return {x, opacity};
  }));
  assert.ok(startupParticles.some(({x, opacity}) => x > .02 && x < .25 && opacity > .15), `the left end has visible particles within 250ms of enabling boost: ${JSON.stringify(startupParticles)}`);
  const particle = page.locator('.dcp-fast-path').first();
  const travel = await particle.evaluate(el => {
    const animation = el.getAnimations()[0], {duration,delay} = animation.effect.getTiming();
    animation.pause(); animation.currentTime = delay + duration * 1.2;
    const before = new DOMMatrix(getComputedStyle(el).transform).m41;
    animation.currentTime = delay + duration * 1.7;
    const after = new DOMMatrix(getComputedStyle(el).transform).m41;
    animation.play(); return {before,after,width:el.getBoundingClientRect().width};
  });
  assert.ok(travel.before > travel.after && Math.abs(travel.before - travel.after - travel.width * .5) < .1, `particles travel right to left across the entire track at a steady speed: ${JSON.stringify(travel)}`);
  assert.match(await page.locator('.dcp-ticks i[data-filled]').first().evaluate(el => getComputedStyle(el).animationName), /dcp-boost-tick-travel/, 'filled ticks depart before the fast stream settles');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await particle.evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await slider.press('Escape');
  await page.locator('.dcp-picker-panel').waitFor({state:'detached'});
  await trigger.click();
  await page.getByRole('dialog').evaluate(async el => {
    await Promise.all(el.getAnimations().map(animation => animation.finished));
  });
  assert.equal(await boost.getAttribute('aria-pressed'), 'true', 'closing the menu preserves the cosmetic toggle');
  assert.equal(await page.locator('.dcp-codex-effort').getAttribute('data-boost-phase'),'active','reopening skips the activation transition');
  assert.equal(await page.locator('.dcp-ticks i[data-filled]').first().evaluate(el=>getComputedStyle(el).opacity),'0');
  await boost.press('Space');
  assert.equal(await boost.getAttribute('aria-pressed'), 'false');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.dcp-fast-clip')).visibility === 'hidden');
  assert.equal(await page.locator('.dcp-ticks i[data-filled]').first().evaluate(el => getComputedStyle(el).opacity), '1', 'ticks return after disabling boost');
  assert.equal(await page.evaluate(() => window.completed), 0);
  await page.evaluate(() => {window.originalTitle = document.querySelector('.dcp-effort-title span'); window.originalPanel = document.querySelector('.dcp-picker-panel');});
  await slider.press('Home');
  await page.waitForFunction(() => window.completed === 1);
  const samples = await page.evaluate(() => window.samples);
  assert.ok(samples.length >= 2, '延迟投影期间采集多个显示帧');
  assert.ok(samples.some(sample => sample.pending) && samples.some(sample => !sample.pending), '覆盖请求等待与已完成但投影未到达的两个阶段');
  assert.equal(samples.every(sample => sample.title === 'low'), true, 'the draft does not revert while the host projection is delayed');
  for (const key of ['triggerOpacity', 'rowOpacity', 'sliderOpacity', 'panelOpacity']) assert.equal(samples.every(sample => sample[key] === '1'), true, `${key} remains stable while selecting`);
  assert.equal(await page.evaluate(() => window.originalTitle === document.querySelector('.dcp-effort-title span') && window.originalPanel === document.querySelector('.dcp-picker-panel')), true, 'tier changes preserve the title and panel nodes');
  assert.equal(await page.locator('.dcp-effort-title span').evaluate(el => getComputedStyle(el).animationName), 'none');
  assert.equal(await trigger.innerText(), '选择推理强度');
  await page.locator('.dcp-model-link').click();
  assert.equal(await trigger.innerText().then(text => text.replace(/\s+/g, ' ')), 'Fixture Model low');
  assert.equal(await trigger.locator('.dcp-trigger-placeholder').count(), 0);
  assert.deepEqual(await page.locator('.dcp-model-group-title').allTextContents(), ['Fixture', 'Relay']);
  assert.equal(await page.getByRole('menuitemradio', {checked:true}).count(), 1);
  assert.equal(await page.locator('[data-badge]').count(), 0, 'model rows use catalog names without temporary host badges');
  assert.deepEqual(await page.locator('.dcp-model-name').allTextContents(), ['Fixture Model', 'Fixture Model']);
  const selected = page.getByRole('menuitemradio', {checked:true});
  await selected.focus(); await selected.press('ArrowDown');
  assert.equal(await page.getByRole('group', {name:'Relay',exact:true}).getByRole('menuitemradio').evaluate(el => el === document.activeElement), true, 'keyboard navigation crosses provider headings');
  await page.getByRole('menuitemradio').last().press('ArrowUp');
  assert.equal(await selected.evaluate(el => el === document.activeElement), true);
  await page.getByRole('dialog').screenshot({path:resolve(project,'test-results/grouped-models.png')});
  await selected.press('Escape');
  await page.evaluate(() => {window.failNext = true;});
  await slider.press('ArrowRight');
  await page.getByRole('alert').waitFor();
  assert.equal(await slider.getAttribute('aria-valuetext'), 'low', 'failed selection restores the actual tier');
  assert.equal(await page.getByRole('alert').innerText(), 'Fixture selection failed');
  assert.deepEqual(errors, []);
  console.log('PICKER_STATE_OK: delayed projection, stable appearance, pane label, and failure rollback');
} finally {
  await browser.close();
}
